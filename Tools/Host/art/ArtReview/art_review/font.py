for _character, _rows in {**_LETTERS, **_DIGITS}.items():
    _GLYPHS[_character] = tuple(_rows.split())


def glyph(character: str) -> tuple[str, ...]:
    if len(character) != 1 or not 32 <= ord(character) <= 126:
        raise ValueError("font supports ASCII 32..126")
    return _GLYPHS.get(character, _GLYPHS.get(character.upper(), _GLYPHS["?"]))


def draw_text(image: RGBAImage, x: int, y: int, text: str, color: Color = (255, 255, 255, 255), scale: int = 1) -> None:
    if scale < 1:
        raise ValueError("font scale must be positive")
    cursor = x
    for character in text:
        pattern = glyph(character)
        for row, bits in enumerate(pattern):
            for column, bit in enumerate(bits):
                if bit == "1":
                    for sy in range(scale):
                        for sx in range(scale):
                            px, py = cursor + column * scale + sx, y + row * scale + sy
                            if 0 <= px < image.width and 0 <= py < image.height:
                                image.set(px, py, color)
        cursor += 6 * scale


def text_size(text: str, scale: int = 1) -> tuple[int, int]:
    return (max(0, len(text) * 6 - 1) * scale, 7 * scale)
